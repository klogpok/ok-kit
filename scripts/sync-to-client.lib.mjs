// The logic of `sync-to-client.mjs`: which kit files the copy holds, the import rewrite, the
// SYNCED.md note, and writing or checking a target. Tested by `sync-to-client.test.mjs`.
import { mkdir, readdir, readFile, rm, rmdir, stat, writeFile } from 'node:fs/promises';
import { dirname, join, posix, relative, resolve, sep } from 'node:path';
import ts from 'typescript';

export const SYNCED_MD = 'SYNCED.md';
const MARKER = '<!-- Generated by scripts/sync-to-client.mjs of @vplans/ui-kit. -->';
const SOURCE_LINE = /^Source: .*$/m;

/** The note a sync writes at the root of the copy. */
export function renderSyncedMd({ commit, dirty }) {
  return `${MARKER}

# @vplans/ui-kit (synced copy)

Generated by \`scripts/sync-to-client.mjs\` in the ok-kit-20 repo. Do not edit these files: a fix
goes into the kit, and the kit is synced again.

Source: \`@vplans/ui-kit\` at commit \`${commit}\`, working tree ${dirty ? 'dirty' : 'clean'}.

## Sync again

From the ok-kit-20 repo:

\`\`\`sh
pnpm sync:client            # writes this folder
pnpm sync:client --check    # exits non-zero when this folder differs from the kit
pnpm sync:client --verify   # compiles a copy with the client's tsconfig options and sass
\`\`\`

## Use the kit in a screen

Import from an entry point's \`public-api\` with a relative path
(\`import { UiButton } from '../ui-kit/button/public-api';\`). Each consumer brings what the kit
needs itself:

- render \`<ui-embed-styles />\` (from \`theme/public-api\`) in its template: it loads the tokens and
  layout classes while it is rendered, without the kit's global base styles;
- put \`provideUiLabels(...)\` (from \`core/public-api\`), keyed on \`LOCALE_ID\`, in its own
  \`providers\`.
`;
}

/**
 * Paths that differ between `plan` and the folder `target` (missing: everything is added). The
 * source line of SYNCED.md is not compared: a new kit commit alone does not make the copy stale.
 */
export async function checkTarget(target, plan) {
  return diff(plan, await readTree(target), true);
}

/**
 * Makes `target` hold exactly `plan`: writes new and changed files, deletes files the plan no
 * longer has and the folders they leave empty. Writes nothing outside `target`, refuses a target
 * whose parent folder is missing, and refuses a non-empty target that is not the output of an
 * earlier sync (no SYNCED.md of this script). Returns the differences it applied.
 */
export async function syncTarget(target, plan) {
  const root = resolve(target);
  const inside = (path) => {
    const full = resolve(root, path);
    if (!full.startsWith(root + sep)) throw new Error(`${path} is outside the target ${root}`);
    return full;
  };
  for (const path of plan.keys()) inside(path);
  if (!(await isFolder(dirname(root)))) {
    throw new Error(`the parent folder ${dirname(root)} of the target does not exist`);
  }
  const existing = await readTree(root);
  if (existing.size > 0 && !String(existing.get(SYNCED_MD) ?? '').startsWith(MARKER)) {
    throw new Error(
      `${root} has files that sync-to-client.mjs did not write (no ${SYNCED_MD} of it)`,
    );
  }
  const changes = diff(plan, existing, false);
  for (const path of [...changes.added, ...changes.changed]) {
    await mkdir(dirname(inside(path)), { recursive: true });
    await writeFile(inside(path), plan.get(path));
  }
  for (const path of changes.removed) {
    await rm(inside(path));
    for (let folder = dirname(inside(path)); folder !== root; folder = dirname(folder)) {
      if ((await readdir(folder)).length > 0) break;
      await rmdir(folder);
    }
  }
  return changes;
}

/** Every file under `root` as a map of `/`-separated relative path to content; empty if missing. */
export async function readTree(root) {
  const tree = new Map();
  if (!(await isFolder(root))) return tree;
  const walk = async (folder) => {
    for (const item of await readdir(folder, { withFileTypes: true })) {
      const full = join(folder, item.name);
      if (item.isDirectory()) await walk(full);
      else tree.set(relative(root, full).split(sep).join('/'), await readFile(full));
    }
  };
  await walk(root);
  return new Map([...tree].sort(([a], [b]) => (a < b ? -1 : 1)));
}

function diff(plan, existing, ignoreSource) {
  const same = (path) => {
    const want = String(plan.get(path));
    const have = String(existing.get(path));
    return ignoreSource && path === SYNCED_MD
      ? want.replace(SOURCE_LINE, '') === have.replace(SOURCE_LINE, '')
      : Buffer.from(plan.get(path)).equals(existing.get(path));
  };
  const keys = [...plan.keys()];
  return {
    added: keys.filter((path) => !existing.has(path)).sort(),
    changed: keys.filter((path) => existing.has(path) && !same(path)).sort(),
    removed: [...existing.keys()].filter((path) => !plan.has(path)).sort(),
  };
}

async function isFolder(path) {
  try {
    return (await stat(path)).isDirectory();
  } catch {
    return false;
  }
}

const ENTRY_IMPORT = /^@vplans\/ui-kit\/([a-z][a-z0-9-]*)$/;

/** Folders that only serve the kit's own build, docs or tests, whatever they hold. */
const SKIPPED_FOLDERS = new Set(['src', 'docs', 'tokens', 'node_modules']);
/** Files that only serve the kit's own build, docs or tests. */
const SKIPPED_FILE =
  /(\.spec\.ts|\.stories\.ts|^ng-package\.json|^package\.json|^tsconfig.*\.json|\.mdx?)$/;

/**
 * What a sync writes. `files` maps each path inside the copy (with `/` separators, sorted) to its
 * content: every folder of `kit` (`projects/ui-kit`) that has a `public-api.ts`, plus `styles/`,
 * without specs, stories, package and build configs, docs and test setup. `.ts` files get their
 * imports rewritten by `rewriteImports`; `rewritten` counts those imports.
 */
export async function planSync(kit) {
  const files = new Map();
  let rewritten = 0;
  const folders = [];
  for (const item of await readdir(kit, { withFileTypes: true })) {
    if (!item.isDirectory() || skippedFolder(item.name)) continue;
    const names = await readdir(join(kit, item.name));
    if (item.name === 'styles' || names.includes('public-api.ts')) folders.push(item.name);
  }
  for (const folder of folders.sort()) {
    for (const file of await listFiles(kit, folder)) {
      const data = await readFile(join(kit, file));
      if (file.endsWith('.ts')) {
        const result = rewriteImports(String(data), file);
        rewritten += result.count;
        files.set(file, result.text);
      } else {
        files.set(file, data);
      }
    }
  }
  return { files: new Map([...files].sort(([a], [b]) => (a < b ? -1 : 1))), rewritten };
}

function skippedFolder(name) {
  return name.startsWith('.') || name.startsWith('test-setup') || SKIPPED_FOLDERS.has(name);
}

/** Files under `root/folder`, as `/`-separated paths relative to `root`, without skipped ones. */
async function listFiles(root, folder) {
  const files = [];
  for (const item of await readdir(join(root, folder), { withFileTypes: true })) {
    const path = `${folder}/${item.name}`;
    if (item.isDirectory()) {
      if (!item.name.startsWith('.')) files.push(...(await listFiles(root, path)));
    } else if (!SKIPPED_FILE.test(item.name) && !item.name.startsWith('test-setup')) {
      files.push(path);
    }
  }
  return files;
}

/**
 * Rewrites every `'@vplans/ui-kit/<entry>'` module specifier of a TypeScript file to the relative
 * `'../<entry>/public-api'`. `file` is the file's path inside the copy, with `/` separators.
 * Comments are left alone. Throws when `@vplans/ui-kit` is still named outside a comment.
 */
export function rewriteImports(text, file) {
  const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const edits = [];
  const leftovers = [];
  const visit = (node) => {
    if (ts.isStringLiteralLike(node) && node.text.includes('@vplans/ui-kit')) {
      const match = ENTRY_IMPORT.exec(node.text);
      if (match && isModuleSpecifier(node)) {
        const start = node.getStart(source);
        const quote = text[start];
        edits.push({ start, end: node.end, value: quote + relativeEntry(file, match[1]) + quote });
      } else {
        leftovers.push(source.getLineAndCharacterOfPosition(node.getStart(source)).line + 1);
      }
    } else if (ts.isTemplateExpression(node) && node.getText(source).includes('@vplans/ui-kit')) {
      leftovers.push(source.getLineAndCharacterOfPosition(node.getStart(source)).line + 1);
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
  if (leftovers.length > 0) {
    throw new Error(
      `${file}:${leftovers.join(',')}: @vplans/ui-kit is still named outside a comment`,
    );
  }
  let next = text;
  for (const edit of edits.reverse()) {
    next = next.slice(0, edit.start) + edit.value + next.slice(edit.end);
  }
  return { text: next, count: edits.length };
}

function isModuleSpecifier(node) {
  const parent = node.parent;
  return (
    ((ts.isImportDeclaration(parent) || ts.isExportDeclaration(parent)) &&
      parent.moduleSpecifier === node) ||
    (ts.isCallExpression(parent) &&
      parent.expression.kind === ts.SyntaxKind.ImportKeyword &&
      parent.arguments[0] === node) ||
    (ts.isExternalModuleReference(parent) && parent.expression === node) ||
    (ts.isLiteralTypeNode(parent) && ts.isImportTypeNode(parent.parent))
  );
}

function relativeEntry(file, entry) {
  const path = posix.relative(posix.dirname(file), `${entry}/public-api`);
  return path.startsWith('.') ? path : `./${path}`;
}
